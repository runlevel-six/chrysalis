// Package storage keeps attachment files (docs/DESIGN.md §7.3). The local
// backend writes under the data directory; an S3-compatible backend can
// implement the same interface.
package storage

import (
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
)

// Store holds opaque blobs by key.
type Store interface {
	Put(ctx context.Context, key string, data []byte) error
	// Open returns the blob; the caller closes it.
	Open(ctx context.Context, key string) (io.ReadSeekCloser, error)
	Delete(ctx context.Context, key string) error
}

var ErrNotFound = errors.New("storage: not found")

// Keys are generated by the app (ULIDs plus a suffix), never taken from a
// client, but checking them anyway means a bad key can never escape the
// storage directory.
var validKey = regexp.MustCompile(`^[0-9A-Za-z][0-9A-Za-z._-]{1,127}$`)

func checkKey(key string) error {
	if !validKey.MatchString(key) || key == "." || key == ".." {
		return fmt.Errorf("storage: invalid key %q", key)
	}
	return nil
}

// Local stores blobs as files under dir, spread across subdirectories by the
// key's first two characters so no single directory grows huge.
type Local struct{ dir string }

func NewLocal(dir string) (*Local, error) {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return nil, fmt.Errorf("storage: create %s: %w", dir, err)
	}
	return &Local{dir: dir}, nil
}

func (l *Local) path(key string) string {
	return filepath.Join(l.dir, key[:2], key)
}

// Put writes atomically: a temporary file in the same directory, then a
// rename, so a crash mid-write never leaves a half-written blob behind.
func (l *Local) Put(_ context.Context, key string, data []byte) error {
	if err := checkKey(key); err != nil {
		return err
	}
	p := l.path(key)
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(p), ".tmp-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }() // no-op after a successful rename
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), p)
}

func (l *Local) Open(_ context.Context, key string) (io.ReadSeekCloser, error) {
	if err := checkKey(key); err != nil {
		return nil, err
	}
	f, err := os.Open(l.path(key))
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrNotFound
	}
	return f, err
}

func (l *Local) Delete(_ context.Context, key string) error {
	if err := checkKey(key); err != nil {
		return err
	}
	err := os.Remove(l.path(key))
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	return err
}
